#!/usr/bin/env python3.14
# -*- coding: utf-8 -*-
"""The `update-presentation-data` command: refresh the presentation deck's data file.

The deck under `docs/presentation/` (served at `/story/`) opens straight from disk
(`file://`) without a fetch, so its data is a plain script, `data/history.js`, that sets
`window.HISTORY`. This command rebuilds it from `solutions/problems.json` plus a handful of
project counts. Only public metadata is exported — number, title, difficulty, upstream
solver count, solved flag and date, and file *counts* — never an answer, and nothing read
from inside `solutions/private/`.

Three of its inputs are other verbs' outputs, which is why it runs **last** in any chain of
them: `problems.json` (`summary`), `topics/articles.json` (`update-tags`) and
`docs/commands-index.md` (`update-docs`).

Two fields move on every run whatever else does — the generation date and the commit count —
and the commit count moves *because* this command commits. Rewriting for them alone would
make every run a commit, and every commit the next run's reason to commit again. So they
ride along with a real change and never cause one: a file whose problems and other counts
are current is left alone.

Exposed as the `update-presentation-data` shell command: `solver "update-presentation-data"`
to refresh, `solver "update-presentation-data --check"` to verify (exit 1 if stale, writing
nothing).
"""
from __future__ import annotations

__all__ = ['update_presentation_data']

import re
from datetime import datetime
from json import JSONDecodeError, dumps, loads
from pathlib import Path
from subprocess import run
from typing import Any

from solver.config import ExitCodes, config
from solver.core.git import commit_regenerated
from solver.core.progress import read_problems
from solver.shell import console, register
from solver.utils.quips import quips

#: The fields of each problem row, in order — the deck indexes rows by this list.
FIELDS: list[str] = ['number', 'title', 'level', 'pct', 'solvers', 'solved', 'date']

#: What precedes the JSON payload in the generated script.
_PREFIX = 'window.HISTORY = '

#: The payload fields that change on every run and so must not, alone, cause a write.
_VOLATILE: tuple[str, ...] = ('generated',)
_VOLATILE_PROJECT: tuple[str, ...] = ('commits',)


def _target() -> Path:
    """The generated data file the deck loads."""
    return config.docs_dir / 'presentation' / 'data' / 'history.js'


def _written() -> str:
    """This command's one output, as the repo-relative path its commit names."""
    return _target().relative_to(config.root_dir).as_posix()


def _iso(date: object) -> str:
    """'Thu, 2 Jul 2015, 17:16' → '2015-07-02T17:16', or '' when absent or unreadable."""
    try:
        return datetime.strptime(str(date), '%a, %d %b %Y, %H:%M').strftime('%Y-%m-%dT%H:%M')
    except ValueError:
        return ''


def _project_stats() -> dict[str, int]:
    """Counts for the "what changed" slide — file names and counts only, never file contents."""
    solutions = config.solutions_dir
    commits = run(['git', 'rev-list', '--count', 'HEAD'], cwd=config.root_dir,
                  capture_output=True, text=True, check=False).stdout.strip()
    articles = loads(config.topics_index_file.read_text(encoding='utf-8'))['articles']
    commands = re.findall(r'^#### Command:',
                          (config.docs_dir / 'commands-index.md').read_text(encoding='utf-8'),
                          flags=re.MULTILINE)
    return {'python': sum(1 for _ in solutions.rglob('p*_s*.py')),
            'c': sum(1 for _ in solutions.rglob('p*_s*.c')),
            'notes': sum(1 for _ in solutions.rglob('notes.html')),
            'articles': len(articles),
            'articles_final': sum(1 for a in articles if a.get('status') == 'final'),
            'commands': len(commands),
            'commits': int(commits) if commits.isdigit() else 0}


def _render(payload: dict[str, Any]) -> str:
    """*payload* as the script the deck loads."""
    return (f'// Generated by `update-presentation-data` from solutions/problems.json — do not edit.\n'
            f'{_PREFIX}{dumps(payload, ensure_ascii=False, separators=(",", ":"))};\n')


def _read_current() -> dict[str, Any] | None:
    """The payload the data file holds now; None when it is absent or unreadable."""
    try:
        text = _target().read_text(encoding='utf-8')
        start = text.index(_PREFIX) + len(_PREFIX)
        payload: dict[str, Any] = loads(text[start:].strip().removesuffix(';'))
        return payload
    except (OSError, ValueError, JSONDecodeError):
        return None


def _material(payload: dict[str, Any]) -> dict[str, Any]:
    """*payload* without the fields that move on every run — what decides a write."""
    project = {k: v for k, v in payload.get('project', {}).items() if k not in _VOLATILE_PROJECT}
    return {**{k: v for k, v in payload.items() if k not in _VOLATILE}, 'project': project}


# Maintainer, the `summary` floor: the deck's data is derived from the progress file that
# `summary` (maintainer) writes, and it is the last link of the progress upload's chain. It
# writes one generated data file and no code.
@register(requires='maintainer', quietable=True)
def update_presentation_data(check: bool = False) -> int:
    """Refresh the presentation deck's data from the progress file.

    Rebuilds `docs/presentation/data/history.js` — the script the deck at `/story/` loads —
    from `solutions/problems.json`, the article index, the command catalogue and counts of
    the solution files. Only public metadata is exported: never an answer, and nothing read
    from inside `solutions/private/`.

    The generation date and commit count are refreshed only alongside a real change, never
    on their own, so a current file is left alone.

    A file that changed is committed, staging that one file and nothing beside it.

    Args:
        check: Write nothing and fail if the data file is out of date. Defaults to False,
            which refreshes it in place.
    """
    problems = read_problems(config.static_file_problems)
    if not problems:
        console.print(f'[error]error:[/error] {config.static_file_problems.relative_to(config.root_dir)} '
                      'is missing or empty (run [accent]summary[/accent])')
        return ExitCodes.EXIT_ERROR
    rows = [[number, record.get('title', ''), record.get('level', ''), record.get('pct', ''),
             record.get('solvers', ''), bool(record.get('solved')), _iso(record.get('date', ''))]
            for number, record in sorted(problems.items())]
    payload: dict[str, Any] = {'generated': datetime.now().strftime('%Y-%m-%d'),
                               'fields': FIELDS,
                               'problems': rows,
                               'project': _project_stats()}
    current = _read_current()
    if current is not None and _material(current) == _material(payload):
        if check:
            console.print('[success]presentation data is up to date[/success]')
            return ExitCodes.EXIT_OK
        console.print('[muted]presentation data already up to date[/muted]')
        # Still offered to the committer: an earlier run may have written the file and failed
        # to commit it. Clean is a no-op.
        return commit_regenerated('update-presentation-data', quips['update-presentation-data'],
                                  [_written()])
    if check:
        console.print('[error]presentation data out of date[/error] '
                      '(run [accent]update-presentation-data[/accent])')
        return ExitCodes.EXIT_ERROR

    target = _target()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_render(payload), encoding='utf-8')
    solved = sum(1 for row in rows if row[5])
    counted = sum(1 for row in rows if row[4] != '')
    summary = f'{len(rows)} problems, {solved} solved, {counted} with solver counts'
    console.print(f'[success]updated[/success] {_written()} ([accent]{summary}[/accent])')
    return commit_regenerated('update-presentation-data', quips['update-presentation-data'],
                              [_written()], [f'{_written()}: {summary}'])
